;; Independent JVM: same request must stop at the persisted nonce, before query.
(require '[clojure.string :as str])
(def root (or (System/getenv "KOTOBASE_ORACLE_ROOT") (throw (ex-info "oracle root required" {}))))
(def source (slurp (str root "/oracle/awai-174/governed_persistent_forest_replay.clj")))
(def prefix (first (str/split source #"\(let \[before" 2)))
(load-string (str/replace prefix "fixture-persistent-entry-20261114" "fixture-nonce-crash-20261114"))
(let [snapshot (store/read-store (str output "/store")) names (keys (:state snapshot))
      before (:root snapshot) r (run! identity)
      after (:root (store/read-store (str output "/store")))]
 (assert (= [:basis] (:events r)))
 (assert (= :nonce-replayed (get-in r [:result :error :kotobase.authority-window/reason])))
 (assert (= before after))
 (assert (not (.exists (java.io.File. (str output "/result.edn")))))
 (assert (.exists (java.io.File. (str output "/nonce-committed.signal"))))
 (assert (= 2 (count names)))
 (assert (= 1 (count (filter #(str/starts-with? % "awai.kotobase-ref/nonce/v1/") names))))
 (assert (= 1 (count (filter #(str/starts-with? % "awai.ipld-forest-group/kotobase-blocks/") names))))
 (prn {:replay :refused :events (:events r) :root :unchanged :result :absent :catalog :nonce-only :fresh-process true :pass true}))
(shutdown-agents)
