;; Hosted reference test with an exclusive single writer, not distributed CAS.
(require '[kotobase.nonce-store :as nonce] '[otehon.storage :as store] '[otehon.kotobase-forest-blocks :as forest])
(def mode (first *command-line-args*))
(def base (or (System/getenv "NONCE_FOREST_OUTPUT") (throw (ex-info "output required" {}))))
(def tool (or (System/getenv "FOREST_TOOL") (throw (ex-info "tool required" {}))))
(when (= mode "write")
 (assert (.mkdir (java.io.File. base)))
 (assert (.mkdir (java.io.File. (str base "/stage"))))
 (store/init! (str base "/store")))
(def backend (forest/open-backend (str base "/store") (str base "/stage") tool))
(defn c [scope] (nonce/consumer {:backend backend :scope scope :single-writer? true}))
(case mode
 "write" (do (assert (true? ((c "tenant/alice") "nonce-1")))
             (assert (false? ((c "tenant/alice") "nonce-1")))
             (prn {:mode mode :first :accepted :repeat :refused :pass true}))
 "read" (do (assert (false? ((c "tenant/alice") "nonce-1")))
            (assert (true? ((c "tenant/bob") "nonce-1")))
            (assert (true? ((c "tenant/alice") "nonce-2")))
            (prn {:mode mode :previous :refused :other-scope :accepted :fresh :accepted :pass true}))
 (throw (ex-info "write/read required" {})))
(shutdown-agents)
