(require '[clojure.string :as str] '[clojure.set])
(def project (System/getenv "KOTOBASE_ORACLE_ROOT"))
(load-string (first (str/split (slurp (str project "/oracle/awai-174/governed_linked_registry_memory.clj")) #"\(let \[before \(memory/snapshot memory-backend\)" 2)))
(require '[kotobase.hosted-receipt-publication :as hosted] '[kotobase.storage.core :as storage] '[awai.fs.car :as car])
(import '[java.security MessageDigest] '[java.util Random Arrays])
(def base (System/getenv "LINKED_GOVERNED_BASE"))
(def dir (str base "/store"))
(def stage (str base "/stage"))
(assert (.isDirectory (java.io.File. dir)))
(assert (.isDirectory (java.io.File. stage)))
(def prior-ids (clojure.edn/read-string (slurp (str base "/advance-ids.edn"))))
(def backend (fb/open-backend dir stage tool))
(defn open-db [b] (core/open {:storage b :encrypt-fn identity :decrypt-fn identity :blind-fn pr-str :visible? (constantly true)}))
(def rng (Random. 174532))
(def attachments (mapv (fn [_] (let [b (byte-array (* 600 1024)) _ (.nextBytes rng b) d (mapv #(bit-and 255 %) (.digest (MessageDigest/getInstance "SHA-256") b))] {:cid (car/cid-str (car/cid-bytes car/codec-raw d)) :bytes b})) (range 2)))
(defn groups [] (set (filter #(str/starts-with? % "awai.ipld-forest-group/kotobase-blocks/") (keys (:state (store/read-store dir))))))
(def pre-groups (atom nil))
(defn ro-db [get-block]
  (open-db (reify storage/IBlockStore
             (-put-blocks! [_ _] (throw (ex-info "read-only" {})))
             (-get-blocks [_ cids] (into {} (keep (fn [cid] (when-let [b (get-block cid)] [cid b]))) cids))
             storage/IRefStore (-read-ref [_ name] (storage/-read-ref backend name))
             (-compare-and-set-ref! [_ _ _ _] (throw (ex-info "read-only" {})))
             storage/IBackendCapabilities (-capabilities [_] (storage/-capabilities backend)))))
(def callbacks (hosted/callbacks {:stage-bundle! (fn [ports _ _] (reset! pre-groups (groups)) (doseq [{:keys [cid bytes]} attachments] ((:put! ports) cid bytes)))
                                 :encrypt! identity :open-read-db! ro-db
                                 :verify-bundle! (fn [get-block _ _ _] (every? (fn [{:keys [cid bytes]}] (Arrays/equals ^bytes bytes ^bytes (get-block cid))) attachments))}))
(assert (= (:commit prior-ids) (:cid (storage/-read-ref backend "linked-governed-advance"))))
(assert (nil? (storage/-read-ref backend "linked-governed-denied")))
(def publication (fb/receipt-publication-adapter backend "linked-governed-denied" nil (:build! callbacks) (:verify! callbacks)))
(def events (atom []))
(def denied-delegation (chain/verify (chain/present token) {:roots #{(ed/public-key seed)} :request {:req/kind :datom/read-protected :req/resource "kotoba://ungranted" :req/now 1700000000}}))
(assert (false? (:dango/allowed? denied-delegation)))
(def evaluations (atom 0))
(def request* (assoc request :nonce "linked-governed-forest-deny-03"))
(def req (-> opts (dissoc :commit!) (assoc :request request* :commit {:database (open-db backend) :expected-basis-cid (:commit prior-ids) :receipt-cid-fn id/value-cid :publication publication} :authority-decision real-decision :authorize! (fn [q] {:allowed? (:dango/allowed? denied-delegation) :projection (set (:find q)) :basis basis :policy-cid pcid}) :evaluate! (fn [& _] (swap! evaluations inc) (throw (ex-info "unexpected evaluation" {}))))))
(def basis-config (config events identity))
(def nonce-config {:backend backend :single-writer? true})
(def result (try (read/read-registry-linked-persistent! req basis-config (verification-config) nonce-config evidence) (throw (ex-info "denied read returned rows" {})) (catch clojure.lang.ExceptionInfo e (ex-data e))))
(assert (= :authority-denied (:kotobase.governed-execution/reason result)))
(assert (zero? @evaluations))
(def cid (:kotobase.governed-execution/deny-receipt-cid result))
(def commit (:kotobase.governed-execution/deny-receipt-commit-cid result))
(def records (:receipt/records (causal/receipt-at (open-db backend) commit cid)))
(assert (= 3 (count records)))
(assert (= :deny (:authority/decision (first records))))
(assert (nil? (:result/root (first records))))
(assert (= authority-receipt (second records)))
(assert (= commit (:cid (storage/-read-ref backend "linked-governed-denied"))))
(assert (= (:commit prior-ids) (:cid (storage/-read-ref backend "linked-governed-advance"))))
(assert (= (:commit prior-ids) (:receipt/basis-cid (causal/receipt-at (open-db backend) commit cid))))
(assert (= 3 (count (:receipt/records (causal/receipt-at (open-db backend) (:commit prior-ids) (:cid prior-ids))))))
(assert (true? (link/verify! {:link (nth records 2) :request request* :query query :execution-receipt (first records) :authority-receipt (second records) :value-cid id/value-cid :verify (:verify opts)})))
(def added (clojure.set/difference (groups) @pre-groups))
(assert (= 1 (count added)))
(assert (= 2 (count (get-in (catalog/recover-group dir (subs (first added) (count "awai.ipld-forest-group/"))) [:group :archives]))))
(assert (= :nonce-replayed (try (read/read-registry-linked-persistent! req basis-config (verification-config) nonce-config evidence) nil (catch Exception e (:kotobase.authority-window/reason (ex-data e))))))
(spit (str base "/deny-ids.edn") (pr-str {:cid cid :commit commit}))
