;; Hosted GiB integration with an authenticated, persisted authority decision.
(require '[clojure.string :as str])
(def script (System/getenv "GIB_LINKED_WRITER"))
(load-string (first (str/split (slurp script) #"\(def result \(read/read-registry-linked-persistent!" 2)))
(require '[kotobase.authority-commit-attestation :as attest])
(def auth-dir (str base "/authority-store"))
(def auth-stage (str base "/authority-stage"))
(assert (.mkdir (java.io.File. auth-stage)))
(store/init! auth-dir)
(def auth-backend (fb/open-backend auth-dir auth-stage tool))
(def auth-db (open-db auth-backend))
(def auth-basis (core/commit-at! auth-db nil [["authority" "scope" "fixture"]]))
(def causal-decision (trust/decide (assoc trust-input :causal.trust/basis-cid auth-basis)))
(def receipt (trust/receipt (assoc authority-receipt
 :causal.receipt/basis-cid auth-basis :causal.receipt/decision causal-decision)))
(def auth-ack (causal/persist-decision! auth-db receipt auth-basis))
(def auth-commit (:receipt/commit-cid auth-ack))
(def seed (vec (repeat 32 5)))
(def unsigned-attestation {:format attest/format-id :commit-cid auth-commit :issuer "did:key:fixture-authority" :tenant tenant :epoch 7})
(def attestation (assoc unsigned-attestation :signature (sign "authority" seed unsigned-attestation)))
(def entry {:key/id "authority" :key/algorithm :ed25519 :key/material (ed/public-key seed)})
(def registry (fn [scope] (if (= scope {:role :issuer :tenant tenant :epoch 7}) [entry] [])))
(def config* {:attestation attestation :registry registry :algorithm :ed25519
 :issuer-authorized? (fn [{:keys [issuer key]}] (and (= issuer "did:key:fixture-authority") (= (:key/id key) "authority")))
 :verify-with (fn [{:keys [key payload-cid signature-value]}] (ed/verify (:key/material key) (payload-bytes payload-cid) signature-value))})
(def auth! (causal/decision-receipt-authenticator auth-db {:commit-cid auth-commit :verify-commit! (attest/verifier config*)}))
(def ctx {:authority-receipt receipt :request request* :query query})
(assert (true? (auth! ctx)))
(def root-before (:root (store/read-store dir)))
(doseq [cfg [(assoc-in config* [:attestation :signature :signature/value] (vec (repeat 64 0)))
             (assoc config* :registry (constantly []))]]
 (let [bad (causal/decision-receipt-authenticator auth-db {:commit-cid auth-commit :verify-commit! (attest/verifier cfg)})]
  (assert (not (true? (try (bad ctx) (catch Exception _ false)))))))
(assert (not (true? (try (auth! (assoc-in ctx [:request :tenant] "wrong")) (catch Exception _ false)))))
(assert (= root-before (:root (store/read-store dir))))
(def result (read/read-registry-linked-persistent! (assoc req :authority-decision causal-decision) cfg verify-cfg {:backend backend :single-writer? true}
 {:authority-receipt receipt :verify-authority! auth!}))
(def cid (get-in result [:provenance :receipt-cid]))
(def commit (get-in result [:provenance :receipt-commit-cid]))
(assert (= 1 (count (:rows result))))
(assert (= 3 (count (:receipt/records (causal/receipt-at (open-db backend) commit cid)))))
(spit (str base "/authenticated-ids.edn") (pr-str {:receipt cid :commit commit :authority-commit auth-commit :authority-basis auth-basis :attestation attestation}))
(prn {:file-blocks 1024 :file-sha expected-sha :authority :persisted-scoped-signed :invalid-signature :refused :missing-key :refused :wrong-tenant :refused :rows 1 :linked-records 3 :pass true})
(shutdown-agents)
