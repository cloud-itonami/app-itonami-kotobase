(defn verify-file! []
 (let [manifest-bytes ((:get-block file-view) file-cid) parsed (first (car/cbor-decode (mapv #(bit-and 255 %) manifest-bytes) 0)) md (MessageDigest/getInstance "SHA-256") chunks (get parsed "chunks")]
   (assert (= 1024 (count chunks)))
   (doseq [[i c] (map-indexed vector chunks)] (let [bytes ((:get-block file-view) (car/cid-str (get-in c ["cid" :bytes])))] (assert (= (get c "length") (alength ^bytes bytes))) (.update md ^bytes bytes)) (when (zero? (mod (inc i) 256)) (prn {:file-verified (inc i)}) (flush)))
